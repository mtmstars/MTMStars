-- MTM Stars Supabase setup / upgrade
-- Run this once in Supabase SQL Editor.
-- Safe to run again: existing tables/settings are preserved.

create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  price numeric not null default 0,
  tag text default '',
  category text default '',
  rate numeric default 5,
  n integer default 0,
  image_url text default '',
  description text default '',
  active boolean default true,
  featured boolean not null default true,
  sort_order integer default 0,
  created_at timestamptz default now()
);

alter table public.products add column if not exists featured boolean not null default true;

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  description text default '',
  image_url text default '',
  sort_order integer default 0,
  active boolean not null default true,
  created_at timestamptz default now()
);

create table if not exists public.site_settings (
  key text primary key,
  value text default ''
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text not null,
  message text not null,
  created_at timestamptz default now()
);

